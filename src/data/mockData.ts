// Helper to generate interactive seats with sleeper & seater mix
export const generateBusSeats = (basePrice: number): Seat[] => {
  const seats: Seat[] = [];
  
  // Lower deck: 12 Sleepers + 6 Seaters
  for (let i = 1; i <= 6; i++) {
    seats.push({
      id: `L${i}A`,
      number: `L${i}A`,
      deck: 'lower',
      type: 'sleeper',
      status: i === 2 ? 'booked' : 'available',
      price: basePrice + 200,
    });
    seats.push({
      id: `L${i}B`,
      number: `L${i}B`,
      deck: 'lower',
      type: 'sleeper',
      status: i === 4 ? 'booked' : 'available',
      price: basePrice + 200,
    });
  }
  for (let i = 1; i <= 6; i++) {
    seats.push({
      id: `LS${i}`,
      number: `S${i}`,
      deck: 'lower',
      type: 'seater',
      status: i === 1 ? 'booked' : 'available',
      price: basePrice,
    });
  }

  // Upper deck: 12 Sleepers
  for (let i = 1; i <= 6; i++) {
    seats.push({
      id: `U${i}A`,
      number: `U${i}A`,
      deck: 'upper',
      type: 'sleeper',
      status: i === 3 ? 'booked' : 'available',
      price: basePrice + 350,
    });
    seats.push({
      id: `U${i}B`,
      number: `U${i}B`,
      deck: 'upper',
      type: 'sleeper',
      status: i === 5 ? 'booked' : 'available',
      price: basePrice + 350,
    });
  }

  return seats;
};

